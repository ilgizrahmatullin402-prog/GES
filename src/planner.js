const DEFAULT_TASK = "Опиши большую задачу, которую хочешь разобрать";

export function createPlan(input) {
  const task = normalizeTask(input);
  const isFallback = task === DEFAULT_TASK;

  return {
    goal: {
      title: "Цель",
      text: isFallback
        ? `${DEFAULT_TASK}. После этого сформулируй один понятный результат, к которому нужно прийти.`
        : `Понять, что именно должно получиться: ${task}. Зафиксировать конечный результат в одном предложении.`
    },
    materials: {
      title: "Материалы",
      items: [
        "Список исходных данных, ссылок, файлов или заметок по задаче.",
        "Люди или сервисы, от которых зависит выполнение.",
        "Ограничения: срок, бюджет, формат результата, уровень качества."
      ]
    },
    firstSteps: {
      title: "Первые шаги",
      items: [
        `Переписать задачу простыми словами: ${task}.`,
        "Разделить работу на 3-5 маленьких действий, которые можно выполнить по очереди.",
        "Выбрать самое короткое действие, которое даст первый видимый результат.",
        "Назначить время для следующей проверки прогресса."
      ]
    },
    risks: {
      title: "Риски",
      items: [
        "Задача может оказаться слишком большой для одного подхода.",
        "Может не хватать материалов, доступа или точного критерия успеха.",
        "Есть риск начать с красивой детали, а не с главного результата."
      ]
    },
    resultCheck: {
      title: "Проверка результата",
      items: [
        "Можно показать итог другому человеку и объяснить за 1 минуту.",
        "Первые шаги выполнены, а не только записаны.",
        "Понятно, что делать дальше и какой следующий маленький результат нужен."
      ]
    }
  };
}

function normalizeTask(input) {
  const task = String(input ?? "").trim().replace(/\s+/g, " ");
  return task || DEFAULT_TASK;
}
